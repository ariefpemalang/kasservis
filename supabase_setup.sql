-- 1. Buat Tabel Profil Pengguna (Role: owner, kasir_wifi, teknisi)
CREATE TABLE IF NOT EXISTS public.profiles (
  id UUID REFERENCES auth.users ON DELETE CASCADE PRIMARY KEY,
  username TEXT UNIQUE NOT NULL,
  name TEXT NOT NULL,
  role TEXT NOT NULL DEFAULT 'kasir_wifi' CHECK (role IN ('owner', 'kasir_wifi', 'teknisi')),
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Buat Tabel Catatan Transaksi (Pemasukan & Pengeluaran)
CREATE TABLE IF NOT EXISTS public.transactions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  book TEXT NOT NULL CHECK (book IN ('WIFI', 'SERVIS', 'PRIBADI')),
  type TEXT NOT NULL CHECK (type IN ('INCOME', 'EXPENSE')),
  amount NUMERIC(15, 2) NOT NULL,
  category TEXT NOT NULL,
  notes TEXT,
  date TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  receipt_url TEXT,
  user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
  user_name TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Aktifkan Fitur REALTIME untuk Tabel Transaksi
ALTER PUBLICATION supabase_realtime ADD TABLE public.transactions;

-- 4. Setup Storage Bucket untuk Foto Bukti Struk / Nota
INSERT INTO storage.buckets (id, name, public) 
VALUES ('receipts', 'receipts', true)
ON CONFLICT (id) DO NOTHING;

-- Kebijakan Akses Storage (Publik bisa lihat foto, user terautentikasi bisa upload)
CREATE POLICY "Public Access" 
ON storage.objects FOR SELECT 
USING (bucket_id = 'receipts');

CREATE POLICY "Authenticated users can upload" 
ON storage.objects FOR INSERT 
WITH CHECK (bucket_id = 'receipts');

-- 5. Row Level Security (RLS)
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.transactions ENABLE ROW LEVEL SECURITY;

-- Kebijakan Profil: Siapapun yang terautentikasi bisa membaca profil
CREATE POLICY "Allow authenticated read profiles" 
ON public.profiles FOR SELECT 
TO authenticated 
USING (true);

CREATE POLICY "Allow authenticated update profiles" 
ON public.profiles FOR ALL 
TO authenticated 
USING (true);

-- Kebijakan Transaksi:
-- Owner: Bisa akses semua buku
-- Kasir WiFi: Hanya akses buku WIFI
-- Teknisi: Hanya akses buku SERVIS
CREATE POLICY "Allow read transactions based on role" 
ON public.transactions FOR SELECT 
TO authenticated 
USING (
  EXISTS (
    SELECT 1 FROM public.profiles 
    WHERE profiles.id = auth.uid() 
    AND (
      profiles.role = 'owner' 
      OR (profiles.role = 'kasir_wifi' AND transactions.book = 'WIFI')
      OR (profiles.role = 'teknisi' AND transactions.book = 'SERVIS')
    )
  )
);

CREATE POLICY "Allow insert transactions based on role" 
ON public.transactions FOR INSERT 
TO authenticated 
WITH CHECK (
  EXISTS (
    SELECT 1 FROM public.profiles 
    WHERE profiles.id = auth.uid() 
    AND (
      profiles.role = 'owner' 
      OR (profiles.role = 'kasir_wifi' AND transactions.book = 'WIFI')
      OR (profiles.role = 'teknisi' AND transactions.book = 'SERVIS')
    )
  )
);

CREATE POLICY "Allow update transactions based on role" 
ON public.transactions FOR UPDATE 
TO authenticated 
USING (
  EXISTS (
    SELECT 1 FROM public.profiles 
    WHERE profiles.id = auth.uid() 
    AND (
      profiles.role = 'owner' 
      OR (profiles.role = 'kasir_wifi' AND transactions.book = 'WIFI')
      OR (profiles.role = 'teknisi' AND transactions.book = 'SERVIS')
    )
  )
);

CREATE POLICY "Allow delete transactions based on role" 
ON public.transactions FOR DELETE 
TO authenticated 
USING (
  EXISTS (
    SELECT 1 FROM public.profiles 
    WHERE profiles.id = auth.uid() 
    AND (
      profiles.role = 'owner' 
      OR (profiles.role = 'kasir_wifi' AND transactions.book = 'WIFI')
      OR (profiles.role = 'teknisi' AND transactions.book = 'SERVIS')
    )
  )
);

-- 6. Trigger Otomatis: Saat User Baru Mendaftar di Auth, otomatis buat row di Profiles
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS trigger AS $$
BEGIN
  INSERT INTO public.profiles (id, username, name, role)
  VALUES (
    new.id,
    COALESCE(new.raw_user_meta_data->>'username', split_part(new.email, '@', 1)),
    COALESCE(new.raw_user_meta_data->>'name', split_part(new.email, '@', 1)),
    COALESCE(new.raw_user_meta_data->>'role', 'kasir_wifi')
  );
  RETURN new;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE PROCEDURE public.handle_new_user();

